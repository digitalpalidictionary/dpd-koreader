#!/usr/bin/env python3
"""Generate dpd/frequency_layout.lua from DPD's frequency template.

The mobile database stores frequency counts as unlabelled vectors
(CstFreq, BjtFreq, SyaFreq, ScFreq). Their labels and row spans exist only in
the upstream template, so extract them once:

    python3 tools/gen_frequency_layout.py <frequency_template.js> [dpd/frequency_layout.lua]

Source: digitalpalidictionary/dpd-db exporter/goldendict/javascript/
frequency_template.js. Regenerate when upstream changes the layout, then run
tools/check_parity_data.lua against the matching database release.
"""

import re
import sys
from pathlib import Path

COLUMNS = ["cst_m", "cst_a", "cst_t", "bjt_m", "bjt_a", "sya_m", "sya_a", "sc_m"]
CORPORA = {"Cst": "cst", "Bjt": "bjt", "Sya": "sya", "Sc": "sc"}
LENGTHS = {"cst": 49, "bjt": 39, "sya": 30, "sc": 19}


def cells(row: str):
    for match in re.finditer(r"<(th|td)([^>]*)>(.*?)</\1>", row, re.S):
        tag, attributes, body = match.groups()
        span = re.search(r'rowspan="(\d+)"', attributes)
        yield tag, attributes, body, int(span.group(1)) if span else 1


def parse(template: str):
    body = template.split("<tbody>", 1)[1].split("</tbody>", 1)[0]
    sections, occupied, line = [], {}, 0
    for row in re.findall(r"<tr[^>]*>(.*?)</tr>", body, re.S):
        column, out = 0, None
        for tag, attributes, text, span in cells(row):
            text = re.sub(r"<[^>]+>", "", text).strip()
            if 'class="vertical-text"' in attributes:
                sections.append({"label": text, "rows": []})
                continue
            if tag == "th":
                out = {"label": text, "cells": []}
                continue
            if 'class="gap"' in attributes:
                continue
            while occupied.get((line, column)):
                column += 1
            value = re.search(r"data\.(Cst|Bjt|Sya|Sc)Freq\[(\d+)\]", text)
            if value:
                corpus = CORPORA[value.group(1)]
                name = COLUMNS[column]
                assert name.startswith(corpus), f"{name} holds {corpus} on line {line}"
                out["cells"].append({"column": name, "index": int(value.group(2)) + 1, "rowspan": span})
            for offset in range(span):
                occupied[(line + offset, column)] = True
            column += 1
        if out is not None:
            sections[-1]["rows"].append(out)
            line += 1
    return sections


def check(sections):
    """Each index appears once. The template may leave trailing vector values
    unshown (SYA has 30 counts, the webapp shows 27); return those."""
    seen = {corpus: [] for corpus in LENGTHS}
    for section in sections:
        for row in section["rows"]:
            for cell in row["cells"]:
                seen[cell["column"].split("_")[0]].append(cell["index"])
    unused = {}
    for corpus, length in LENGTHS.items():
        indices = sorted(seen[corpus])
        assert indices == list(range(1, len(indices) + 1)) and len(indices) <= length, f"{corpus} indices {indices}"
        if len(indices) < length:
            unused[corpus] = list(range(len(indices) + 1, length + 1))
    return unused


def lua(sections, unused) -> str:
    def quote(text):
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        "-- Generated by tools/gen_frequency_layout.py from DPD's frequency_template.js.",
        "-- SPDX-License-Identifier: MIT",
        "-- Do not edit by hand. Indices are 1-based positions in the freq_data vectors.",
        "return {",
        "    columns = { " + ", ".join(quote(c) for c in COLUMNS) + " },",
        "    lengths = { " + ", ".join(f"{k} = {v}" for k, v in LENGTHS.items()) + " },",
        "    -- Vector positions the webapp's template does not display.",
        "    unused = { " + ", ".join(f"{k} = {{ {', '.join(map(str, v))} }}" for k, v in unused.items()) + " },",
        "    sections = {",
    ]
    for section in sections:
        out.append(f"        {{ label = {quote(section['label'])}, rows = {{")
        for row in section["rows"]:
            cells = ", ".join(
                f"{{ column = {quote(c['column'])}, index = {c['index']}"
                + (f", rowspan = {c['rowspan']}" if c["rowspan"] > 1 else "")
                + " }"
                for c in row["cells"]
            )
            out.append(f"            {{ label = {quote(row['label'])}, cells = {{ {cells} }} }},")
        out.append("        } },")
    out += ["    },", "}", ""]
    return "\n".join(out)


def main():
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    target = Path(sys.argv[2] if len(sys.argv) > 2 else "dpd/frequency_layout.lua")
    sections = parse(source)
    unused = check(sections)
    target.write_text(lua(sections, unused), encoding="utf-8")
    rows = sum(len(s["rows"]) for s in sections)
    print(f"{target}: {len(sections)} sections, {rows} rows, not displayed upstream: {unused or 'none'}")


if __name__ == "__main__":
    main()
