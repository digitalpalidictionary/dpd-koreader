#!/usr/bin/env python3
"""Generate dpd/rootmatrix_rules.lua from DPD's root matrix classifier.

The webapp's root matrix groups a root's headwords by part of speech and
the derivation marked in root_base (caus, pass, desid, intens, deno). The
rules are a long if/elif chain in Python; extract them once as data:

    python3 tools/gen_root_matrix_rules.py <root_matrix.py> [dpd/rootmatrix_rules.lua]

Source: digitalpalidictionary/dpd-db db/families/root_matrix.py. Regenerate
when upstream changes it, then run tools/check_rootmatrix_html.lua against
the full database of the matching release.
"""

import ast
import sys
from pathlib import Path


def condition(node):
    """A test as a list of conditions, all of which must hold."""
    if isinstance(node, ast.BoolOp) and isinstance(node.op, ast.And):
        return [c for value in node.values for c in condition(value)]
    if isinstance(node, ast.Compare) and isinstance(node.ops[0], ast.Eq):
        left, right = ast.unparse(node.left), node.comparators[0].value
        if left == "i.pos":
            return [("pos", right)]
        if left == "headword":
            return [("lemma", right)]
    if isinstance(node, ast.Call) and ast.unparse(node.func) == "re.findall":
        pattern, field = node.args[0].value, ast.unparse(node.args[1])
        assert field in ("i.root_base", "i.grammar"), field
        field = field[2:]
        if pattern.startswith("\\b") and pattern.endswith("\\b") and pattern[2:-2].isalpha():
            return [("word", field, pattern[2:-2])]
        assert pattern.isalpha(), pattern
        return [("text", field, pattern)]
    raise AssertionError(f"unsupported test: {ast.unparse(node)}")


def target(statements):
    for statement in statements:
        if isinstance(statement, ast.AugAssign):
            keys = [s.slice.value for s in _subscripts(statement.target)]
            assert len(keys) == 2, ast.unparse(statement)
            return keys
    raise AssertionError("no assignment")


def _subscripts(node):
    out = []
    while isinstance(node, ast.Subscript):
        if isinstance(node.slice, ast.Constant):
            out.append(node)
        node = node.value
    return list(reversed(out))


def chain(node):
    """An if/elif chain as [(conditions, body)], the final else with no conditions."""
    out = []
    while True:
        out.append((condition(node.test), node.body))
        if len(node.orelse) == 1 and isinstance(node.orelse[0], ast.If):
            node = node.orelse[0]
            continue
        if node.orelse:
            out.append(([], node.orelse))
        return out


def rules(tree):
    top = next(n for n in ast.walk(tree) if isinstance(n, ast.If) and ast.unparse(n.test) == "i.pos == 'pr'")
    out = []
    for conditions, body in chain(top):
        nested = next((s for s in body if isinstance(s, ast.If)), None)
        if not conditions and not any(isinstance(s, ast.AugAssign) for s in body):
            continue  # the final "ERROR" branch: the headword is not placed
        if nested is not None:
            steps = [(c, target(b)) for c, b in chain(nested)]
            # Upstream's fut branch has a copy/paste aorist target. Keep this
            # correction here so regenerating the Lua cannot reintroduce it.
            if conditions == [("pos", "fut")]:
                for _, destination in steps:
                    if destination == ["verbs", "aor deno & caus"]:
                        destination[1] = "fut deno & caus"
            out.append({"when": conditions, "chain": steps})
        else:
            out.append({"when": conditions, "target": target(body)})
    return out


def categories(tree):
    init = next(n for n in ast.walk(tree) if isinstance(n, ast.Assign)
                and ast.unparse(n.targets[0]) == "root_matrix[i.root_key]")
    return [(k.value, [r.value for r in v.keys]) for k, v in zip(init.value.keys, init.value.values)]


def lua(cats, rule_list):
    def q(text):
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

    def conds(cs):
        parts = []
        for c in cs:
            if c[0] in ("pos", "lemma"):
                parts.append(f"{{ {c[0]} = {q(c[1])} }}")
            else:
                parts.append(f"{{ {c[0]} = {q(c[2])}, field = {q(c[1])} }}")
        return "{ " + ", ".join(parts) + " }"

    out = [
        "-- Generated by tools/gen_root_matrix_rules.py from DPD's db/families/root_matrix.py.",
        "-- SPDX-License-Identifier: MIT",
        "-- Do not edit by hand. The first rule whose `when` holds places a headword;",
        "-- `word` matches a whole word (Python's \\b), `text` a substring.",
        "return {",
        "    categories = {",
    ]
    for name, rows in cats:
        out.append(f"        {{ name = {q(name)}, rows = {{ {', '.join(q(r) for r in rows)} }} }},")
    out += ["    },", "    rules = {"]
    for rule in rule_list:
        if "target" in rule:
            out.append(f"        {{ when = {conds(rule['when'])}, target = {{ {q(rule['target'][0])}, {q(rule['target'][1])} }} }},")
        else:
            out.append(f"        {{ when = {conds(rule['when'])}, chain = {{")
            for cs, (cat, row) in rule["chain"]:
                out.append(f"            {{ when = {conds(cs)}, target = {{ {q(cat)}, {q(row)} }} }},")
            out.append("        } },")
    out += ["    },", "}", ""]
    return "\n".join(out)


def main():
    tree = ast.parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    target_path = Path(sys.argv[2] if len(sys.argv) > 2 else "dpd/rootmatrix_rules.lua")
    cats, rule_list = categories(tree), rules(tree)
    known = {(name, row) for name, rows in cats for row in rows}
    for rule in rule_list:
        for _, t in rule.get("chain", [(None, rule.get("target"))]):
            assert tuple(t) in known, t
    target_path.write_text(lua(cats, rule_list), encoding="utf-8")
    rows = sum(len(r) for _, r in cats)
    print(f"{target_path}: {len(cats)} categories, {rows} rows, {len(rule_list)} rules")


if __name__ == "__main__":
    main()
